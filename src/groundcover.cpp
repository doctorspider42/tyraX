std::string materialOf(const GroundCover& c) {
    return c.material.empty() ? std::string(kBuiltinMtl) : c.material;
}

std::vector<Entry> covers(const SceneData& sc) {
    std::vector<Entry> out;
    if (!sc.terrain.enabled) return out;
    if (sc.terrainBaseCover.enabled) out.push_back({-1, sc.terrainBaseCover});
    for (size_t l = 0; l < sc.terrainLayers.size(); ++l)
        if (sc.terrainLayers[l].cover.enabled)
            out.push_back({(int)l, sc.terrainLayers[l].cover});
    return out;
}

bool projectUsesBuiltin(const Project& p) {
    for (const SceneData& sc : p.scenes)
        for (const Entry& e : covers(sc))
            if (e.cover.material.empty()) return true;
    return false;
}

int cardsPerTile(const GroundCover& c, float tileUnits, float unitsPerMeter) {
    const float m = unitsPerMeter > 0.0f ? tileUnits / unitsPerMeter : tileUnits;
    const int n = (int)(c.density * m * m + 0.5f);
    return std::clamp(n, 0, kMaxCardsPerTile);
}

std::vector<unsigned char> builtinTuft(int size) {
    const int n = std::max(16, size);
    std::vector<unsigned char> px((size_t)n * n * 4, 0);
    // Transparent texels carry the blades' mid green: a bilinear edge sample
    // mixes toward it instead of toward black (no dark fringe).
    for (size_t i = 0; i < px.size(); i += 4) px[i] = 78, px[i + 1] = 118, px[i + 2] = 40;
    uint32_t s = 0x6a09e667u;
    const float base = (float)(n - 3);  // the roots' row (two clear rows below)
    const int blades = 13;
    for (int b = 0; b < blades; ++b) {
        const float bx = (float)n * (0.2f + 0.6f * prand(s));
        const float h = (float)(n - 6) * (0.45f + 0.55f * prand(s));
        const float lean = ((prand(s) - 0.5f) * 0.9f) * (float)n * 0.35f;
        const float bw = (float)n * (0.035f + 0.025f * prand(s));
        const float tone = 0.8f + 0.35f * prand(s);
        for (int y = 2; y < n - 2; ++y) {
            const float t = (base - (float)y) / h;  // 0 root .. 1 tip
            if (t < 0.0f || t > 1.0f) continue;
            const float cx = bx + lean * t * t;
            const float half = bw * (1.0f - t) + 0.45f;
            for (int x = 2; x < n - 2; ++x) {
                if (std::fabs((float)x + 0.5f - cx) > half) continue;
                unsigned char* p = &px[((size_t)y * n + x) * 4];
                const float r = (34.0f + 120.0f * t) * tone;
                const float g = (62.0f + 150.0f * t) * tone;
                const float bl = (18.0f + 52.0f * t) * tone;
                p[0] = (unsigned char)std::min(255.0f, r);
                p[1] = (unsigned char)std::min(255.0f, g);
                p[2] = (unsigned char)std::min(255.0f, bl);
                p[3] = 255;
            }
        }
    }
    return px;
}

bool writeBuiltin(const std::string& projectDir, std::string* err) {
    namespace fs = std::filesystem;
    const fs::path png = fs::path(projectDir) / kBuiltinPng;
    const fs::path mtl = fs::path(projectDir) / kBuiltinMtl;
    std::error_code ec;
    fs::create_directories(png.parent_path(), ec);
    const int n = 64;
    const std::vector<unsigned char> px = builtinTuft(n);
    std::string bytes;
    stbi_write_png_to_func(
        [](void* ctx, void* data, int size) {
            static_cast<std::string*>(ctx)->append(static_cast<const char*>(data),
                                                   (size_t)size);
        },
        &bytes, n, n, 4, px.data(), n * 4);
    if (bytes.empty() || !writeIfChanged(png, bytes)) {
        if (err) *err = "cannot write " + png.string();
        return false;
    }
    const std::string text =
        "# Generated by TyraX (ground cover) - the built-in grass tuft card\n"
        "newmtl grass-tuft\nKd 1 1 1\nmap_Kd grass-tuft.png\n";
    if (!writeIfChanged(mtl, text)) {
        if (err) *err = "cannot write " + mtl.string();
        return false;
    }
    return true;
}

uint32_t tileSeed(int tx, int tz, int coverIndex) {
    uint32_t h = (uint32_t)tx * 73856093u ^ (uint32_t)tz * 19349663u ^
                 (uint32_t)(coverIndex + 1) * 83492791u;
    h ^= h >> 13;
    h *= 0x5bd1e995u;
    h ^= h >> 15;
    return h;
}

float compositeWeight(int layer, const float* w, int n) {
    float v = layer < 0 ? 1.0f : w[layer];
    for (int k = layer + 1; k < n; ++k) v *= 1.0f - w[k];
    return v;
}

void tileCards(int tx, int tz, int coverIndex, const GroundCover& c, int layer,
               float tileUnits, float unitsPerMeter, const Ground& g,
               std::vector<Card>& out) {
    const int n = cardsPerTile(c, tileUnits, unitsPerMeter);
    uint32_t s = tileSeed(tx, tz, coverIndex);
    const float hw = c.width * unitsPerMeter * 0.5f;
    const float hh = c.height * unitsPerMeter * 0.5f;
    for (int i = 0; i < n; ++i) {
        const float u = prand(s), v = prand(s), thin = prand(s);
        const float sz = prand(s), acc = prand(s), sh = prand(s);
        const float x = ((float)tx + u) * tileUnits;
        const float z = ((float)tz + v) * tileUnits;
        if (acc >= g.weight(layer, x, z)) continue;
        const float m = 1.0f + c.sizeJitter * (sz - 0.5f);
        Card k;
        k.halfW = hw * m;
        k.halfH = hh * m;
        // Sunk a little so a card on a slope never shows a gap under it.
        k.x = x;
        k.y = g.height(x, z) + k.halfH * 0.9f;
        k.z = z;
        k.thin = thin;
        k.shade = 0.8f + 0.2f * sh;
        k.mirror = (i & 1) != 0;
        out.push_back(k);
    }
}

