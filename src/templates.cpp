static std::string sanitizeNamespace(const std::string& name) {
    // Project name -> valid C++ namespace: letters/digits/underscore, no leading digit
    std::string ns;
    for (char c : name) {
        if (isalnum((unsigned char)c) || c == '_')
            ns += c;
        else
            ns += '_';
    }
    if (ns.empty() || isdigit((unsigned char)ns[0])) ns = "Game" + ns;
    if (!ns.empty() && islower((unsigned char)ns[0])) ns[0] = (char)toupper((unsigned char)ns[0]);
    return ns;
}

static std::string fillTemplate(const Project& p, const char* tpl) {
    // docker compose project name: lowercase, must start with letter/digit
    std::string nameLower;
    for (char c : p.name) nameLower += (char)tolower((unsigned char)c);
    if (nameLower.empty() || !isalnum((unsigned char)nameLower[0]))
        nameLower = "tyra-" + nameLower;

    std::string s = tpl;
    s = replaceAll(s, "{{NAME_LOWER}}", nameLower);
    s = replaceAll(s, "{{NAME}}", p.name);
    s = replaceAll(s, "{{NAME_UPPER_NS}}", sanitizeNamespace(p.name));
    s = replaceAll(s, "{{WIDTH}}", std::to_string(p.terrain.width));
    s = replaceAll(s, "{{DEPTH}}", std::to_string(p.terrain.depth));

    const ProjectSettings& st = p.settings;
    s = replaceAll(s, "{{DETAIL}}", std::to_string(st.terrainDetail));
    s = replaceAll(s, "{{CLIP_PRECISE}}", st.clipping == "fast" ? "false" : "true");
    s = replaceAll(s, "{{SKY_R}}", floatLit(st.skyColor[0] * 255.0f));
    s = replaceAll(s, "{{SKY_G}}", floatLit(st.skyColor[1] * 255.0f));
    s = replaceAll(s, "{{SKY_B}}", floatLit(st.skyColor[2] * 255.0f));
    s = replaceAll(s, "{{EYE_HEIGHT}}", floatLit(st.eyeHeight));
    s = replaceAll(s, "{{WALK_SPEED}}", floatLit(st.walkSpeed));
    s = replaceAll(s, "{{LOOK_SPEED}}", floatLit(st.lookSpeed));
    s = replaceAll(s, "{{ORBIT_SPEED}}", floatLit(st.orbitSpeed));
    s = replaceAll(s, "{{GRAVITY}}", floatLit(st.gravity));
    s = replaceAll(s, "{{JUMP_SPEED}}", floatLit(st.jumpSpeed));
    s = replaceAll(s, "{{SKY_DOME}}", st.skyDome ? "true" : "false");
    s = replaceAll(s, "{{SKY_TOP_R}}", floatLit(st.skyTopColor[0] * 255.0f));
    s = replaceAll(s, "{{SKY_TOP_G}}", floatLit(st.skyTopColor[1] * 255.0f));
    s = replaceAll(s, "{{SKY_TOP_B}}", floatLit(st.skyTopColor[2] * 255.0f));
    {
        float lx = st.lightDir[0], ly = st.lightDir[1], lz = st.lightDir[2];
        const float len = std::sqrt(lx * lx + ly * ly + lz * lz);
        if (len > 1e-5f) lx /= len, ly /= len, lz /= len;
        else lx = 0, ly = 1, lz = 0;
        s = replaceAll(s, "{{LIGHT_X}}", floatLit(lx));
        s = replaceAll(s, "{{LIGHT_Y}}", floatLit(ly));
        s = replaceAll(s, "{{LIGHT_Z}}", floatLit(lz));
    }
    s = replaceAll(s, "{{AMBIENT}}", floatLit(st.ambient));
    s = replaceAll(s, "{{DIFFUSE}}", floatLit(st.diffuse));
    return s;
}

bool matchesLegacy(const Project& p, const std::string& relativePath,
                   const std::string& content) {
    const char* tpl = nullptr;
    if (relativePath == "src\\terrain_game.cpp")
        tpl = TPL_GAME_CPP_V1;
    else if (relativePath == "inc\\terrain_game.hpp")
        tpl = TPL_GAME_HPP_V1;
    if (!tpl) return false;
    return content == fillTemplate(p, tpl);
}

// ---------------------------------------------------------------------------
// Flow graph -> C++ script. Object names are resolved to indices at codegen
// time; unknown names produce a comment instead of code.
// ---------------------------------------------------------------------------
std::string flowGraphScript(const Project& p) {
    const std::string ns = sanitizeNamespace(p.name);

    auto objectIndex = [&](const std::string& name) {
        for (size_t i = 0; i < p.objects.size(); ++i)
            if (p.objects[i].name == name) return (int)i;
        return -1;
    };

    // action node -> inline statements
    auto actionCode = [&](const FlowNode& n, const std::string& pad) -> std::string {
        std::ostringstream c;
        const int idx = objectIndex(n.str);
        const bool needsObject = flowNodeType(n.type)->strKind == FlowParamKind::ObjectName;
        if (needsObject && idx < 0) {
            c << pad << "// node " << n.id << " (" << n.type << "): unknown object '"
              << n.str << "'\n";
            return c.str();
        }
        const std::string obj = "ctx.objects[" + std::to_string(idx) + "]";
        if (n.type == "SetSky") {
            c << pad << "ctx.skyColor = Tyra::Color(" << floatLit(n.num[0] * 255.0f) << ", "
              << floatLit(n.num[1] * 255.0f) << ", " << floatLit(n.num[2] * 255.0f) << ");\n";
        } else if (n.type == "ShowObject") {
            c << pad << obj << ".visible = true;\n";
        } else if (n.type == "HideObject") {
            c << pad << obj << ".visible = false;\n";
        } else if (n.type == "ToggleObject") {
            c << pad << obj << ".visible = !" << obj << ".visible;\n";
        } else if (n.type == "MoveObjectBy") {
            for (int a = 0; a < 3; ++a)
                if (n.num[a] != 0.0f)
                    c << pad << obj << ".data.position[" << a << "] += " << floatLit(n.num[a])
                      << ";\n";
            c << pad << obj << ".dirty = true;\n";
        } else if (n.type == "SetObjectColor") {
            for (int a = 0; a < 3; ++a)
                c << pad << obj << ".data.color[" << a << "] = " << floatLit(n.num[a]) << ";\n";
            c << pad << obj << ".dirty = true;\n";
        } else if (n.type == "Log") {
            std::string text = n.str;
            text = replaceAll(text, "\\", "\\\\");
            text = replaceAll(text, "\"", "\\\"");
            c << pad << "TYRA_LOG(\"" << text << "\");\n";
        }
        return c.str();
    };

    // all actions linked to a trigger
    auto linkedActions = [&](int triggerId, const std::string& pad) {
        std::ostringstream c;
        for (const FlowLink& l : p.flowGraph.links) {
            if (l.fromNode != triggerId) continue;
            for (const FlowNode& n : p.flowGraph.nodes) {
                if (n.id != l.toNode) continue;
                const FlowNodeType* t = flowNodeType(n.type);
                if (t && !t->trigger) c << actionCode(n, pad);
            }
        }
        return c.str();
    };

    std::ostringstream out;
    out << "// Generated by tyra-editor from the Flow Graph. Do not edit -\n"
           "// regenerated on every build. Edit the graph in the editor instead.\n"
           "#include \"scripts/script.hpp\"\n\n"
           "namespace "
        << ns
        << " {\n\n"
           "class FlowGraphScript : public Script {\n"
           " public:\n"
           "  void update(ScriptContext& ctx) override {\n"
           "    frame++;\n";

    std::ostringstream members;
    for (const FlowNode& n : p.flowGraph.nodes) {
        const FlowNodeType* t = flowNodeType(n.type);
        if (!t || !t->trigger) continue;
        const std::string body = linkedActions(n.id, "      ");
        if (body.empty()) continue;

        if (n.type == "OnStart") {
            out << "    if (!started) {\n      started = true;\n" << body << "    }\n";
        } else if (n.type == "OnButton") {
            std::string btn = n.str.empty() ? "Cross" : n.str;
            out << "    if (ctx.engine->pad.getClicked()." << btn << ") {\n" << body
                << "    }\n";
        } else if (n.type == "NearObject") {
            const int idx = objectIndex(n.str);
            if (idx < 0) {
                out << "    // node " << n.id << " (NearObject): unknown object '" << n.str
                    << "'\n";
                continue;
            }
            const std::string flag = "near" + std::to_string(n.id);
            members << "  bool " << flag << " = false;\n";
            const float r = n.num[0] > 0.01f ? n.num[0] : 3.0f;
            out << "    {\n      const float dx = ctx.playerPosition.x - ctx.objects[" << idx
                << "].data.position[0];\n      const float dz = ctx.playerPosition.z - "
                   "ctx.objects["
                << idx << "].data.position[2];\n      const bool isNear = dx * dx + dz * dz < "
                << floatLit(r * r) << ";\n      if (isNear && !" << flag << ") {\n"
                << body << "      }\n      " << flag << " = isNear;\n    }\n";
        } else if (n.type == "EverySeconds") {
            int frames = (int)(n.num[0] * 50.0f);
            if (frames < 1) frames = 1;
            out << "    if (frame % " << frames << " == 0) {\n" << body << "    }\n";
        }
    }

    out << "  }\n\n"
           " private:\n"
           "  int frame = 0;\n"
           "  bool started = false;\n"
        << members.str()
        << "};\n\n"
           "}  // namespace "
        << ns << "\n\nTYRA_SCRIPT(" << ns << "::FlowGraphScript);\n";
    return out.str();
}

// inc/model_data.gen.hpp - .obj meshes compiled into the game (pos + normal,
// 6 floats per vertex). Capped per model to stay PS2-friendly.
static std::string modelDataHeader(const Project& p) {
    const std::string ns = sanitizeNamespace(p.name);
    const auto paths = collectModelPaths(p);
    constexpr int kMaxTris = 3000;

    std::ostringstream out;
    out << "// Generated by tyra-editor. Do not edit - regenerated on every build.\n"
           "#pragma once\n\nnamespace "
        << ns
        << " {\n\n"
           "struct ModelData {\n"
           "  const float* verts;  // 6 floats per vertex: x,y,z,nx,ny,nz\n"
           "  int vertexCount;\n"
           "};\n\n"
        << "constexpr int MODEL_COUNT = " << paths.size() << ";\n\n";

    for (size_t m = 0; m < paths.size(); ++m) {
        std::vector<float> data;
        const bool ok =
            objparser::load((std::filesystem::path(p.dir) / paths[m]).string(), data);
        int vertexCount = ok ? (int)(data.size() / 6) : 0;
        if (vertexCount > kMaxTris * 3) {
            out << "// " << paths[m] << ": truncated from " << vertexCount / 3 << " to "
                << kMaxTris << " triangles\n";
            vertexCount = kMaxTris * 3;
        }
        out << "// " << paths[m] << (ok ? "" : " (missing or unparseable)") << "\n";
        out << "constexpr float MODEL_" << m << "_VERTS[] = {";
        for (int i = 0; i < vertexCount * 6; ++i) {
            if (i % 6 == 0) out << "\n    ";
            out << floatLit(data[i]) << ",";
        }
        if (vertexCount == 0) out << "0.0F";  // avoid empty array
        out << "\n};\nconstexpr int MODEL_" << m << "_COUNT = " << vertexCount << ";\n\n";
    }

    out << "inline const ModelData MODELS[MODEL_COUNT > 0 ? MODEL_COUNT : 1] = {\n";
    if (paths.empty()) {
        out << "    {nullptr, 0},\n";
    } else {
        for (size_t m = 0; m < paths.size(); ++m)
            out << "    {MODEL_" << m << "_VERTS, MODEL_" << m << "_COUNT},\n";
    }
    out << "};\n\n}  // namespace " << ns << "\n";
    return out.str();
}

