  const auto& rightJoy = engine->pad.getRightJoyPad();

  // Right stick: look around (stick right = turn right)
  yaw -= axisValue(rightJoy.h) * 0.05F * LOOK_SPEED;
  pitch -= axisValue(rightJoy.v) * 0.035F * LOOK_SPEED;
