      if (outCount + 3 > kMaxClippedVerts) break;
      clippedPool[outCount++] = clippedTriangle[0];
      clippedPool[outCount++] = clippedTriangle[j];
      clippedPool[outCount++] = clippedTriangle[(j + 1) % clippedSize];
