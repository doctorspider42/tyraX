    if (!o.visible || o.data.type == 4) continue;
    const float ox = o.data.position[0];
    const float oz = o.data.position[2];
    const float hx = 0.5F * o.data.scale[0] + playerRadius;
    const float hz = 0.5F * o.data.scale[2] + playerRadius;
