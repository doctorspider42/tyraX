"""Blender -b --factory-startup --python tools/bake-tree-foliage.py.

Original folded leaf geometry -> orthographic Cycles tone/coverage stamp.
Only the checked-in stamp enters the editor; Blender is an authoring dependency.
Optional -- --blend <path> saves the editable source scene.
"""
import math
import random
import sys
from pathlib import Path
import bpy
from mathutils import Vector

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/tree'
OUT.mkdir(parents=True, exist_ok=True)
rng = random.Random(7139)
bpy.ops.object.select_all(action='SELECT')
bpy.ops.object.delete(use_global=False)
verts, faces = [], []

def leaf(x, y, z, angle, length, width):
    # Raised midrib and bent tip give genuine light/shadow variation.
    start = len(verts)
    ca, sa = math.cos(angle), math.sin(angle)
    for u, v, h in [(0,0,0),(.38,-1,-.12),(.48,0,.16),
                     (.38,1,-.08),(1,0,.08)]:
        verts.append((x+ca*u*length-sa*v*width,
                      y+sa*u*length+ca*v*width, z+h*length))
    faces.extend(tuple(start+i for i in f) for f in
                 [(0,1,2),(0,2,3),(1,4,2),(2,4,3)])

def twig(a, b, radius):
    delta = Vector(b)-Vector(a)
    bpy.ops.mesh.primitive_cone_add(vertices=5, radius1=radius,
        radius2=radius*.4, depth=delta.length, location=(Vector(a)+Vector(b))/2)
    obj=bpy.context.object
    obj.rotation_euler=delta.to_track_quat('Z','Y').to_euler()
    obj.data.materials.append(mat)

mat=bpy.data.materials.new('Neutral leaf luminance')
mat.diffuse_color=(.48,.48,.48,1)
mat.use_nodes=True
mat.node_tree.nodes['Principled BSDF'].inputs['Base Color'].default_value=(.48,.48,.48,1)
mat.node_tree.nodes['Principled BSDF'].inputs['Roughness'].default_value=.85
for branch in range(9):
    angle=branch*2.39996
    start=Vector((-.12, -.20, .02))
    end=Vector((math.cos(angle)*rng.uniform(.45,.66),
                math.sin(angle)*rng.uniform(.42,.64),rng.uniform(.01,.13)))
    twig(start,end,.009)
    for j in range(5):
        t=(j+1)/6
        p=start.lerp(end,t)
        for side in [-1,1]:
            leaf(p.x,p.y,p.z+rng.uniform(-.015,.025),
                 angle+side*rng.uniform(.5,1.2),rng.uniform(.19,.29),rng.uniform(.045,.074))
mesh=bpy.data.meshes.new('Folded blades')
mesh.from_pydata(verts,[],faces)
obj=bpy.data.objects.new('Broadleaf spray',mesh)
bpy.context.collection.objects.link(obj)
obj.data.materials.append(mat)
scene=bpy.context.scene
scene.render.engine='CYCLES'
scene.cycles.samples=48
scene.cycles.seed=73
scene.world.color=(.35,.35,.35)
bpy.ops.object.light_add(type='AREA', location=(-1,1,3))
bpy.context.object.data.energy=110
bpy.context.object.data.shape='DISK'
bpy.context.object.data.size=2
bpy.ops.object.camera_add(location=(0,0,4))
scene.camera=bpy.context.object
scene.camera.data.type='ORTHO'
scene.camera.data.ortho_scale=1.55
scene.render.resolution_x=scene.render.resolution_y=128
scene.render.resolution_percentage=100
scene.render.film_transparent=True
scene.view_settings.view_transform='Standard'
scene.render.image_settings.file_format='PNG'
scene.render.image_settings.color_mode='RGBA'
scene.render.filepath=str(OUT/'broadleaf-source.png')
bpy.ops.render.render(write_still=True)
# Load the PNG as non-colour data to retain display-space tones, flip to image
# rows. Zero denotes cutout; 1..255 is luminance (alpha is reconstructed).
img=bpy.data.images.load(scene.render.filepath,check_existing=False)
img.colorspace_settings.name='Non-Color'
pixels=list(img.pixels)
stamp=[]
for y in range(127,-1,-1):
    for x in range(128):
        i=(y*128+x)*4
        stamp.append(max(1,min(255,round(pixels[i]*255))) if pixels[i+3]>=.5 else 0)
header='// Generated by tools/bake-tree-foliage.py; original Blender geometry.\n'
header+='static constexpr unsigned char kBroadleafStamp[128 * 128] = {\n'
header+='\n'.join(','.join(map(str,stamp[i:i+32]))+',' for i in range(0,len(stamp),32))+'\n};\n'
(ROOT/'src/tree_foliage.inc').write_bytes(header.encode())
print('Opaque coverage:',sum(v>0 for v in stamp)/len(stamp))
if '--' in sys.argv:
    args=sys.argv[sys.argv.index('--')+1:]
    if args and args[0]=='--blend':
        bpy.ops.wm.save_as_mainfile(filepath=str(Path(args[1]).resolve()))
